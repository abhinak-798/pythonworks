#DECALRE A LIST OF 5 COLOURS
l=['violet','indigo','blue','green','red']
print(l)

#ADD A NEW COLOUR 'yellow' TO THE LIST
l.append('yellow')
print(l)

#CHANGE THE SECOND COLOUR TO BLACK
l[1]='black'

#PRINT THE UPDATED LIST
print(l)

#PRINT THE SECOND LAST COLOUR
print(l[-2])

#PRINT THE NUMBER OF COLOURS
print(len(l))

#PRINT THE REVERSE OF LIST
print(l[::-1])
